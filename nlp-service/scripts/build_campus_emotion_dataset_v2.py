def read_existing_rows(path: Path) -> dict[str, list[dict[str, str]]]:
    with path.open("r", encoding="utf-8", newline="") as file:
        rows = list(csv.DictReader(file))

    grouped = {label: [] for label in LABEL_ORDER}
    for row in rows:
        grouped[row["emotion_type"]].append(row)
    return grouped


def build_rows(grouped: dict[str, list[dict[str, str]]]) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for label_index, label in enumerate(LABEL_ORDER):
        label_rows = grouped[label] + [
            {
                "id": "",
                "text": text,
                "emotion_type": label,
                "source": "ai_generated",
            }
            for text in ADDITIONAL_SAMPLES[label]
        ]
        if len(label_rows) != 50:
            raise ValueError(f"{label} must have 50 rows, got {len(label_rows)}")

        start_id = label_index * 50 + 1
        for offset, row in enumerate(label_rows):
            rows.append(
                {
                    "id": str(start_id + offset),
                    "text": row["text"],
                    "emotion_type": label,
                    "source": row["source"],
                }
            )
    return rows


def write_rows(path: Path, rows: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=["id", "text", "emotion_type", "source"])
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    input_path = root / "data" / "campus_emotion_samples_v1.csv"
    output_path = root / "data" / "campus_emotion_samples_v2.csv"
    rows = build_rows(read_existing_rows(input_path))
    write_rows(output_path, rows)
    print(f"wrote {len(rows)} rows to {output_path}")


if __name__ == "__main__":
    main()
